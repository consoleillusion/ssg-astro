let routeCache;

/** @returns {Map<string, { actual: string, priority: number }>} */
function routesFor() {
	if (routeCache) {
		return routeCache;
	}

	/** @type {Map<string, { actual: string, priority: number }>} */
	const routes = new Map();
	for (const page of listPages(pagesDir)) {
		const existing = routes.get(page.lookup);
		if (!existing || page.priority < existing.priority) {
			routes.set(page.lookup, { actual: page.actual, priority: page.priority });
		}
	}

	return (routeCache = routes);
}

/**
 * Reload connected pages when the --css file changes. The file lives outside
 * the project root and is not in Vite's module graph, so Vite would not
 * notice it at all; the route handler re-reads it on every request, and this
 * plugin makes connected browsers reload when it changes.
 *
 * @type {import('vite').Plugin}
 */
const userCssReload = {
	name: 'ssg-user-css-reload',
	configureServer(server) {
		if (!userCssPath) {
			// No --css file passed; nothing to watch.
			return;
		}

		const watched = path.resolve(userCssPath);
		server.watcher.add(watched);

		const reload = (file) => {
			if (path.resolve(file) === watched) {
				server.ws.send({ type: 'full-reload' });
			}
		};

		server.watcher.on('change', reload);
		server.watcher.on('add', reload);
		server.watcher.on('unlink', reload);
	},
};

/**
 * Advertise UTF-8 on HTML responses. Bare Markdown/MDX pages render without a
 * <meta charset> (there is no default layout), and without a charset the
 * browser guesses one — which garbles multibyte characters (curly quotes,
 * arrows, dashes). Layout pages already carry <meta charset="UTF-8">; this
 * makes the response header agree, and covers the bare pages too.
 *
 * @type {import('vite').Plugin}
 */
const utf8Html = {
	name: 'ssg-utf8-html',
	configureServer(server) {
		server.middlewares.use((req, res, next) => {
			const writeHead = res.writeHead.bind(res);
			const withCharset = (...args) => {
				// Vite may pass content-type explicitly to writeHead, which
				// takes precedence over res.setHeader — rewrite it in place.
				for (let i = 1; i < args.length; i++) {
					const headers = args[i];
					if (!headers || typeof headers !== 'object' || Array.isArray(headers)) {
						continue;
					}
					const key = Object.keys(headers).find((name) => name.toLowerCase() === 'content-type');
					const ct = key ? String(headers[key]).toLowerCase() : '';
					if (ct.startsWith('text/html') && !ct.includes('charset')) {
						args[i] = { ...headers, [key ?? 'content-type']: 'text/html; charset=utf-8' };
					}
				}
				// Fallback for an implicit writeHead (res.end() with no headers).
				const contentType = res.getHeader('content-type');
				const value = Array.isArray(contentType) ? contentType.join('; ') : contentType;
				const lower = typeof value === 'string' ? value.toLowerCase() : '';
				if (lower.startsWith('text/html') && !lower.includes('charset')) {
					res.setHeader('content-type', 'text/html; charset=utf-8');
				}
				return writeHead(...args);
			};
			// Connect's types for res are loose; writeHead is intact at runtime.
			/** @type {any} */ (res).writeHead = withCharset;
			next();
		});
	},
};

/**
 * Rewrite lowercase URLs to the case-preserving route Astro generates.
 * This keeps links extensionless and lowercase while matching files such as
 * README.md, About.astro, or docs/Getting-Started.md.
 *
 * @type {import('vite').Plugin}
 */
const lowercaseRoutes = {
	name: 'ssg-lowercase-routes',
	enforce: 'pre',
	configureServer(server) {
		// Vite only watches the project root, so changes in the served
		// directory (outside it, behind a symlink) never fire events and the
		// module graph goes stale. Watch the real directory too; without it
		// editing a hosted file requires a server restart.
		server.watcher.add(pagesRealDir);

		const invalidate = () => {
			routeCache = undefined;
			// The --menu markup is baked into each page at compile time; pages
			// must recompile to pick up a newly added or removed page.
			server.moduleGraph.invalidateAll();
			server.ws.send({ type: 'full-reload' });
		};

		server.watcher.on('add', invalidate);
		server.watcher.on('unlink', invalidate);
		server.watcher.on('addDir', invalidate);
		server.watcher.on('unlinkDir', invalidate);

		server.middlewares.use((req, _res, next) => {
			if (!req.url) {
				return next();
			}

			const [rawPath, query] = req.url.split('?');
			let decoded;
			try {
				decoded = decodeURIComponent(rawPath);
			} catch {
				return next();
			}

			const normalized =
				decoded.length > 1 ? decoded.replace(/\/+$/, '') || '/' : decoded;
			if (normalized !== normalized.toLowerCase()) {
				return next();
			}

			const route = routesFor().get(normalized.toLowerCase());
			if (route && route.actual !== decoded) {
				req.url = encodeURI(route.actual) + (query ? `?${query}` : '');
			}

			next();
		});
	},
};

