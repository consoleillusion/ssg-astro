// @ts-check
import fs from 'node:fs';
import path from 'node:path';

import { defineConfig } from 'astro/config';

import mdx from '@astrojs/mdx';

import svelte from '@astrojs/svelte';

import { listPages } from './src/routes.js';

const notFoundFiles = ['404.astro', '404.html', '404.md', '404.mdx'];
const indexFiles = ['index.astro', 'index.html', 'index.md', 'index.mdx'];

const root = process.cwd();
const pagesDir = path.join(root, 'src', 'pages');
// The pages directory is a symlink to the served directory, which lives
// outside the project root. Resolve it so we can watch it (see below).
const pagesRealDir = fs.realpathSync(pagesDir);

const has404Page = notFoundFiles.some((file) => fs.existsSync(path.join(pagesDir, file)));
// Any index page (including one generated by an earlier astro-ssg, which is
// never touched) wins; the default page only exists when none of these do.
const hasIndexPage = indexFiles.some((file) => fs.existsSync(path.join(pagesDir, file)));
const defaultPageDisabled =
	process.env.SSG_NO_DEFAULT_PAGE === '1' ||
	fs.existsSync(path.join(root, '.no-default-page'));

/**
 * Serve a built-in default page at / when the directory has no index page, and
 * a helpful 404 page that describes the supported file types and, when the
 * directory has no index page, links to the pages that do exist. Both routes
 * are injected here so no file is ever added to or removed from the served
 * directory.
 *
 * @type {import('astro').AstroIntegration}
 */
const missingPage = {
	name: 'ssg-missing-page',
	hooks: {
		'astro:config:setup': ({ injectRoute }) => {
			if (defaultPageDisabled) {
				return;
			}

			// Serve the default page from the cache instead of writing an
			// index.html into the served directory.
			if (!hasIndexPage) {
				injectRoute({
					pattern: '/',
					entrypoint: './src/missing/Index.astro',
				});
			}

			// Leave a user-provided 404 page alone.
			if (has404Page) {
				return;
			}

			injectRoute({
				pattern: '/404',
				entrypoint: './src/missing/Index.astro',
			});
		},
	},
};

const themeNames = ['sakura', 'sakura-dark', 'sakura-dark-solarized', 'sakura-earthly', 'sakura-ink', 'sakura-pink', 'sakura-radical', 'sakura-vader', 'milligram', 'skeleton'];
const requestedTheme = (process.env.SSG_THEME ?? '').trim().toLowerCase();
const theme = themeNames.includes(requestedTheme)
	? requestedTheme
	: '';

const userCssPath = (process.env.SSG_CSS_PATH ?? '').trim();
const userCssRoute = '/astro-ssg-user.css';

/**
 * Serve the selected theme stylesheet from node_modules and add it to
 * pages that do not already get it from Layout.astro (for example Markdown
 * pages).
 *
 * @type {import('astro').AstroIntegration}
 */
const themeStyles = {
	name: 'ssg-theme-styles',
	hooks: {
		'astro:config:setup': ({ injectRoute, injectScript }) => {
			if (!theme) {
				return;
			}

			injectRoute({
				pattern: `/${theme}.css`,
				entrypoint: './src/theme/css.ts',
			});

			injectScript(
				'page',
				`
if (!document.querySelector('link[data-ssg-theme]')) {
	const link = document.createElement('link');
	link.rel = 'stylesheet';
	link.href = ${JSON.stringify(`/${theme}.css`)};
	link.dataset.ssgTheme = ${JSON.stringify(theme)};
	document.head.appendChild(link);
}
`
			);
		},
	},
};

/**
 * Serve a user-provided CSS file at a well-known route and add it to pages
 * that do not already get it from Layout.astro (for example Markdown pages).
 * The file is read from its original path on every request, so edits are
 * picked up without a restart.
 *
 * @type {import('astro').AstroIntegration}
 */
const userStyles = {
	name: 'ssg-user-styles',
	hooks: {
		'astro:config:setup': ({ injectRoute, injectScript }) => {
			if (!userCssPath) {
				return;
			}

			injectRoute({
				pattern: userCssRoute,
				entrypoint: './src/theme/user-css.ts',
			});

			injectScript(
				'page',
				`
if (!document.querySelector('link[data-ssg-css]')) {
	const link = document.createElement('link');
	link.rel = 'stylesheet';
	link.href = ${JSON.stringify(userCssRoute)};
	link.dataset.ssgCss = 'true';
	document.head.appendChild(link);
}
`
			);
		},
	},
};

let routeCache;

/** @returns {Map<string, { actual: string, priority: number }>} */
function routesFor() {
	if (routeCache) {
		return routeCache;
	}

	/** @type {Map<string, { actual: string, priority: number }>} */
	const routes = new Map();
	for (const page of listPages(pagesDir)) {
		const existing = routes.get(page.lookup);
		if (!existing || page.priority < existing.priority) {
			routes.set(page.lookup, { actual: page.actual, priority: page.priority });
		}
	}

	return (routeCache = routes);
}

/**
 * Reload connected pages when the --css file changes. The file lives outside
 * the project root and is not in Vite's module graph, so Vite would not
 * notice it at all; the route handler re-reads it on every request, and this
 * plugin makes connected browsers reload when it changes.
 *
 * @type {import('vite').Plugin}
 */
const userCssReload = {
	name: 'ssg-user-css-reload',
	configureServer(server) {
		if (!userCssPath) {
			// No --css file passed; nothing to watch.
			return;
		}

		const watched = path.resolve(userCssPath);
		server.watcher.add(watched);

		const reload = (file) => {
			if (path.resolve(file) === watched) {
				server.ws.send({ type: 'full-reload' });
			}
		};

		server.watcher.on('change', reload);
		server.watcher.on('add', reload);
		server.watcher.on('unlink', reload);
	},
};

/**
 * Rewrite lowercase URLs to the case-preserving route Astro generates.
 * This keeps links extensionless and lowercase while matching files such as
 * README.md, About.astro, or docs/Getting-Started.md.
 *
 * @type {import('vite').Plugin}
 */
const lowercaseRoutes = {
	name: 'ssg-lowercase-routes',
	enforce: 'pre',
	configureServer(server) {
		// Vite only watches the project root, so changes in the served
		// directory (outside it, behind a symlink) never fire events and the
		// module graph goes stale. Watch the real directory too; without it
		// editing a hosted file requires a server restart.
		server.watcher.add(pagesRealDir);

		const invalidate = () => {
			routeCache = undefined;
		};

		server.watcher.on('add', invalidate);
		server.watcher.on('unlink', invalidate);
		server.watcher.on('addDir', invalidate);
		server.watcher.on('unlinkDir', invalidate);

		server.middlewares.use((req, _res, next) => {
			if (!req.url) {
				return next();
			}

			const [rawPath, query] = req.url.split('?');
			let decoded;
			try {
				decoded = decodeURIComponent(rawPath);
			} catch {
				return next();
			}

			const normalized =
				decoded.length > 1 ? decoded.replace(/\/+$/, '') || '/' : decoded;
			if (normalized !== normalized.toLowerCase()) {
				return next();
			}

			const route = routesFor().get(normalized.toLowerCase());
			if (route && route.actual !== decoded) {
				req.url = encodeURI(route.actual) + (query ? `?${query}` : '');
			}

			next();
		});
	},
};

// https://astro.build/config
export default defineConfig({
	integrations: [missingPage, themeStyles, userStyles, mdx(), svelte()],
	vite: {
		plugins: [lowercaseRoutes, userCssReload],
	},
});
