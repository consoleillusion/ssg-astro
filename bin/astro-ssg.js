#!/usr/bin/env node
// @ts-check
import { spawn, spawnSync } from "node:child_process"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { cac } from "cac"
import { compareVersions } from "compare-versions"
import { globSync } from "tinyglobby"

/**
 * @typedef {{ version: string }} PackageJson
 * @typedef {"sakura" | "sakura-dark" | "sakura-dark-solarized" | "sakura-earthly" | "sakura-ink" | "sakura-pink" | "sakura-radical" | "sakura-vader" | "milligram" | "skeleton"} Theme
 * @typedef {{ dir?: string, noDefaultPage: boolean, theme: Theme | null, port: string | null, host: string | null, css: string | null, menu: boolean, edit: boolean }} ServeOptions
 * @typedef {{ dir?: string, noDefaultPage: boolean, theme: Theme | null, css: string | null, menu: boolean }} BuildOptions
 * @typedef {import("node:child_process").SpawnOptions} SpawnOptions
 * @typedef {{
 *   file: string,
 *   actual: string,
 *   priority: number,
 * }} SourcePage
 * @typedef {{
 *   command: string,
 *   installArgs: string[],
 *   devArgs: (astroArgs: string[]) => string[],
 *   buildArgs: string[],
 *   shell: boolean,
 * }} PackageManager
 */

const packageRoot = fileURLToPath(new URL("..", import.meta.url))
const templateDir = path.join(packageRoot, "template")
const packageJson = /** @type {PackageJson} */ (
  JSON.parse(fs.readFileSync(path.join(packageRoot, "package.json"), "utf8"))
)

const MINIMUM_NODE = "22.23.4"
/** @type {readonly string[]} */
const INDEX_FILES = ["index.astro", "index.html", "index.md", "index.mdx", "index.typ"]
/** Source page types in duplicate-route priority order. */
/** @type {readonly string[]} */
const PAGE_EXTENSIONS = [".astro", ".html", ".md", ".mdx", ".typ"]
/** Types that `astro-ssg build` turns into a .html file. */
/** @type {readonly string[]} */
const BUILD_SOURCE_EXTENSIONS = [".astro", ".md", ".mdx", ".typ"]
// Mirrors template/src/routes.js. Compiled pages are deliberately ranked
// below every source type so they never shadow a newer source file.
const GENERATED_HTML_MARKER = "<!-- astro-ssg:generated -->"
/** @type {readonly Theme[]} */
const THEMES = ["sakura", "sakura-dark", "sakura-dark-solarized", "sakura-earthly", "sakura-ink", "sakura-pink", "sakura-radical", "sakura-vader", "milligram", "skeleton"]
const DEFAULT_THEME = "sakura"
// Marker left by the default page generated by astro-ssg <= 0.1.1. Such a file
// is never modified or deleted; the marker only lets us log an accurate message.
const GENERATED_INDEX_MARKER = "<!-- astro-ssg:generated-index -->"
const TEMPLATE_VERSION = "32"
const RUNNING_WITH_BUN = Boolean(process.versions.bun)

/** @param {string} message @returns {never} */
const fail = (message) =>
  (console.error(`astro-ssg: ${message}`), process.exit(1))

const defaultCacheDir = () =>
  process.env.ASTRO_SSG_CACHE
    ? path.resolve(process.env.ASTRO_SSG_CACHE)
    : process.platform === "win32"
      ? path.join
        ( process.env.LOCALAPPDATA ?? path.join(os.homedir(), "AppData", "Local")
        , "astro-ssg"
        )
      : path.join
        ( process.env.XDG_CACHE_HOME ?? path.join(os.homedir(), ".cache")
        , "astro-ssg"
        )

const CACHE_DIR = defaultCacheDir()
const PAGES_DIR = path.join(CACHE_DIR, "src", "pages")
const TEMPLATE_VERSION_PATH = path.join(CACHE_DIR, ".template-version")

// The lockfiles pin prebuilt native packages for both glibc and musl. The
// variant for the other libc cannot be dlopen'd, so it is dead weight
// (~50 MB).
/** @type {Record<"glibc" | "musl", readonly string[]>} */
const LIBC_PACKAGES = {
  // Delete on glibc (musl variants)
  glibc: [
    "lightningcss-linux-x64-musl",
    "lightningcss-linux-arm64-musl",
    "@img/sharp-linuxmusl-x64",
    "@img/sharp-libvips-linuxmusl-x64",
    "@img/sharp-linuxmusl-arm64",
    "@img/sharp-libvips-linuxmusl-arm64",
    "@rolldown/binding-linux-x64-musl",
    "@rolldown/binding-linux-arm64-musl",
  ],
  // Delete on musl (glibc variants)
  musl: [
    "lightningcss-linux-x64-gnu",
    "lightningcss-linux-arm64-gnu",
    "@img/sharp-linux-x64",
    "@img/sharp-libvips-linux-x64",
    "@img/sharp-linux-arm64",
    "@img/sharp-libvips-linux-arm64",
    "@rolldown/binding-linux-x64-gnu",
    "@rolldown/binding-linux-arm64-gnu",
  ],
}

/** @returns {"glibc" | "musl" | null} */
const detectLibc = () => {
  if (process.platform !== "linux") return null
  try {
    const report = /** @type {{ header?: { glibcVersionRuntime?: string } } | undefined} */ (
      process.report?.getReport?.()
    )
    if (report?.header?.glibcVersionRuntime) return "glibc"
  } catch {
    // Fall through to the ldd heuristic.
  }
  try {
    return /musl/i.test(fs.readFileSync("/usr/bin/ldd", "utf8")) ? "musl" : null
  } catch {
    return null
  }
}

/** @param {string} target @returns {number} */
const dirSize = (target) => {
  try {
    const stat = fs.statSync(target)
    if (!stat.isDirectory()) return stat.size
    return fs
      .readdirSync(target)
      .reduce((sum, name) => sum + dirSize(path.join(target, name)), 0)
  } catch {
    return 0
  }
}

/**
 * Remove prebuilt packages for the foreign libc from the cache's
 * node_modules. Called after every install; deleting directories that
 * already vanished is a no-op.
 * @param {string} nodeModulesDir
 */
const pruneForeignLibcPackages = (nodeModulesDir) => {
  const libc = detectLibc()
  if (!libc) return undefined
  const removed = LIBC_PACKAGES[libc].reduce(
    (acc, name) => {
      const target = path.join(nodeModulesDir, name)
      if (!fs.existsSync(target)) return acc
      const bytes = dirSize(target)
      removePath(target)
      return { count: acc.count + 1, bytes: acc.bytes + bytes }
    },
    { count: 0, bytes: 0 }
  )
  return removed.count > 0
    ? console.log(
        `removed ${removed.count} prebuilt packages for the foreign libc (${Math.round(removed.bytes / 1024 / 1024)} MB)`
      )
    : undefined
}

const checkNodeVersion = () =>
  RUNNING_WITH_BUN || compareVersions(process.versions.node, MINIMUM_NODE) >= 0
    ? undefined
    : fail(`Node.js ${MINIMUM_NODE} or newer is required; found ${process.versions.node}.`)

/** @param {string | undefined} dir @returns {string} */
const resolveServeDir = (dir) => {
  const serveDir = path.resolve(dir ?? ".")
  try {
    return fs.statSync(serveDir).isDirectory()
      ? serveDir
      : fail(`${serveDir} is not a directory.`)
  } catch (error) {
    const err = /** @type {NodeJS.ErrnoException} */ (error)
    return err.code === "ENOENT"
      ? fail(`${serveDir} does not exist.`)
      : (() => { throw error })()
  }
}

/** @param {string} target */
const removePath = (target) =>
  ((result) => result)(
    (() => {
      try {
        return ((stat) =>
          stat.isDirectory() && !stat.isSymbolicLink()
            ? fs.rmSync(target, { recursive: true, force: true })
            : fs.unlinkSync(target)
        )(fs.lstatSync(target))
      } catch (error) {
        const err = /** @type {NodeJS.ErrnoException} */ (error)
        return err.code === "ENOENT" ? undefined : (() => { throw error })()
      }
    })()
  )

/**
 * Make the cache writable. The template may come from a read-only source
 * (for example the Nix store), and the cache must stay writable so npm can
 * update package-lock.json and install node_modules.
 *
 * @param {string} dir
 */
const makeWritable = (dir) => {
  try {
    fs.chmodSync(dir, 0o755)
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const target = path.join(dir, entry.name)
      entry.isDirectory() ? makeWritable(target) : fs.chmodSync(target, 0o644)
    }
  } catch {
    // Best effort; surfaces later if npm actually fails.
  }
}

/** @param {string} serveDir */
const assertCacheIsSafe = (serveDir) =>
  ((cache, served) =>
    served === cache ||
    served.startsWith(`${cache}${path.sep}`) ||
    cache.startsWith(`${served}${path.sep}`)
      ? fail("The cache directory and the served directory must not contain each other. Set ASTRO_SSG_CACHE somewhere else.")
      : undefined
  )(path.resolve(CACHE_DIR), path.resolve(serveDir))

/** @param {string} filePath @returns {boolean} */
const isGeneratedIndex = (filePath) => {
  try {
    return fs.readFileSync(filePath, "utf8").includes(GENERATED_INDEX_MARKER)
  } catch {
    return false
  }
}

/** @param {string} filePath @returns {boolean} */
const isGeneratedHtml = (filePath) => {
  if (path.extname(filePath).toLowerCase() !== ".html") return false
  try {
    return fs.readFileSync(filePath, "utf8").includes(GENERATED_HTML_MARKER)
  } catch {
    return false
  }
}

/**
 * The pages in a directory that need (or already have) compiled HTML,
 * following the same route and duplicate-priority rules as the Astro template.
 * @param {string} dir
 * @returns {SourcePage[]}
 */
const listSourcePages = (dir) => {
  /** @type {Map<string, SourcePage>} */
  const pages = new Map()
  const files = globSync(["**/*.{astro,html,md,mdx,typ}"], {
    cwd: dir,
    ignore: ["**/_*", "**/_*/**", "**/node_modules/**"],
    followSymbolicLinks: false,
  })

  for (const raw of files) {
    const file = raw.replaceAll(path.sep, "/")
    const segments = file.split("/")
    const name = segments.pop() ?? ""
    const extension = path.posix.extname(name)
    const extensionPriority = PAGE_EXTENSIONS.indexOf(extension)
    if (extensionPriority === -1) continue
    const priority = isGeneratedHtml(path.join(dir, file))
      ? PAGE_EXTENSIONS.length
      : extensionPriority

    const base = name.slice(0, -extension.length)
    // Dynamic routes cannot be linked or built to a single HTML file.
    if (base.includes("[")) continue

    const isIndex = base === "index"
    const route = isIndex ? segments : [...segments, base]
    const actual =
      route.length === 0 ? "/" : `/${route.join("/")}${isIndex ? "/" : ""}`
    const lookup = actual.toLowerCase().replace(/\/+$/, "") || "/"
    const existing = pages.get(lookup)
    if (existing && existing.priority <= priority) continue
    pages.set(lookup, { file, actual, priority })
  }

  return [...pages.values()]
}

/** @param {string} dir */
const assertTypstAvailable = (dir) => {
  const typstFiles = globSync(["**/*.typ"], {
    cwd: dir,
    ignore: ["**/_*", "**/_*/**", "**/node_modules/**"],
    followSymbolicLinks: false,
  })
  if (typstFiles.length === 0) return
  const binary = process.env.TYPST_BIN || "typst"
  const result = spawnSync(binary, ["--version"], { encoding: "utf8" })
  if (result.error || result.status !== 0) {
    fail(
      `${typstFiles.length} .typ file(s) need Typst, but "${binary}" could not be run. Install Typst with HTML export support (https://typst.app), or set TYPST_BIN to its path.`
    )
  }
}

/** @param {string} value @returns {value is Theme} */
const isTheme = (value) =>
  /** @type {readonly string[]} */ (THEMES).includes(value)

/** @param {unknown} value @returns {Theme | null} */
const normalizeTheme = (value) => {
  if (value === undefined || value === null || value === false) return null
  const theme =
    value === true ? DEFAULT_THEME : String(value).trim().toLowerCase()
  if (theme === "") return DEFAULT_THEME
  return isTheme(theme)
    ? theme
    : fail(
        `Unknown theme "${String(value)}". Choose one of: ${THEMES.join(", ")}. Put a directory argument before --theme.`
      )
}

/** @param {unknown} value @returns {string | null} */
const normalizeCss = (value) => {
  if (value === undefined || value === null || value === false) return null
  const file = path.resolve(String(value))
  if (path.extname(file).toLowerCase() !== ".css")
    fail(`--css must point to a .css file; got "${String(value)}".`)
  /** @type {fs.Stats} */
  let stat
  try {
    stat = fs.statSync(file)
  } catch {
    return fail(`--css file does not exist: ${file}`)
  }
  if (!stat.isFile()) fail(`--css is not a file: ${file}`)
  try {
    fs.accessSync(file, fs.constants.R_OK)
  } catch {
    return fail(`--css file is not readable: ${file}`)
  }
  return file
}

/** @param {string} serveDir @param {boolean} noDefaultPage @returns {string} */
const indexMessage = (serveDir, noDefaultPage) => {
  const existing = INDEX_FILES.filter((file) =>
    fs.existsSync(path.join(serveDir, file))
  )
  const staleGenerated =
    existing.includes("index.html")
    && isGeneratedIndex(path.join(serveDir, "index.html"))
  const hasUserIndex = existing.some((file) =>
    file !== "index.html"
      ? true
      : !staleGenerated && !isGeneratedHtml(path.join(serveDir, file))
  )
  if (hasUserIndex) return "Found an index page; / will serve it."
  if (staleGenerated)
    return "Found an index.html generated by an earlier astro-ssg version; serving it as-is and leaving it untouched. Delete it manually if you want the cache-served default page instead."
  return noDefaultPage
    ? "No index page found; / will return 404 (default page disabled)."
    : "No index page found; / will show the generated default page."
}

/** @returns {boolean} */
const cacheIsCurrent = () => {
  try {
    return (
      fs.existsSync(path.join(CACHE_DIR, "package.json")) &&
      fs.existsSync(PAGES_DIR) &&
      fs.readFileSync(TEMPLATE_VERSION_PATH, "utf8").trim() === TEMPLATE_VERSION
    )
  } catch {
    return false
  }
}

/** @param {string} serveDir */
const initializeCache = (serveDir) =>
  ( assertCacheIsSafe(serveDir)
  , console.log(`copying template to ${CACHE_DIR}`)
  , fs.rmSync(CACHE_DIR, { recursive: true, force: true })
  , fs.mkdirSync(CACHE_DIR, { recursive: true })
  , fs.cpSync(templateDir, CACHE_DIR, { recursive: true })
  , makeWritable(CACHE_DIR)
  , fs.writeFileSync(TEMPLATE_VERSION_PATH, TEMPLATE_VERSION)
  , fs.rmSync(path.join(CACHE_DIR, ".classless"), { force: true })
  , fs.rmSync(path.join(CACHE_DIR, ".no-default-page"), { force: true })
  , fs.mkdirSync(path.dirname(PAGES_DIR), { recursive: true })
  , removePath(PAGES_DIR)
  , fs.symlinkSync(serveDir, PAGES_DIR, process.platform === "win32" ? "junction" : "dir")
  , console.log(`serving ${serveDir} as ${PAGES_DIR}`)
  , undefined
  )

/** @returns {PackageManager} */
const packageManager = () =>
  RUNNING_WITH_BUN
    ? ( { command: process.execPath
        , installArgs: ["install"]
        , devArgs: (astroArgs) => ["run", "dev", ...astroArgs]
        , buildArgs: ["run", "build"]
        , shell: false
        }
      )
    : ( { command: process.platform === "win32" ? "npm.cmd" : "npm"
        , installArgs: ["install", "--no-audit", "--no-fund"]
        , devArgs: (astroArgs) =>
            astroArgs.length > 0 ? ["run", "dev", "--", ...astroArgs] : ["run", "dev"]
        , buildArgs: ["run", "build"]
        , shell: process.platform === "win32"
        }
      )

/**
 * @param {string} command
 * @param {string[]} args
 * @param {SpawnOptions} [options]
 * @returns {Promise<number>}
 */
const run = (command, args, options = {}) =>
  /** @type {Promise<number>} */ (new Promise((resolve, reject) =>
    ((child) =>
      ( child.on("error", reject)
      , child.on("close", (code, signal) => resolve(code ?? (signal ? 1 : 0)))
      , child
      )
    )(
      spawn
        ( command
        , args
        , { stdio: "inherit"
          , shell: process.platform === "win32"
          , ...options
          }
        )
    )
  ))

/** @param {unknown} port @returns {string | null} */
const normalizePort = (port) =>
  port === undefined || port === null
    ? null
    : ((value) =>
        /^\d+$/.test(value) ? value : fail("--port must be a number.")
      )(String(port))

/** @param {unknown} host @returns {string | null} */
const normalizeHost = (host) =>
  host === undefined || host === null || host === false
    ? null
    : host === true
      ? "0.0.0.0"
      : String(host)

/** @param {ServeOptions} options @returns {string[]} */
const astroArgsFromOptions = (options) =>
  [ options.port !== null ? ["--port", options.port] : []
  , options.host !== null ? ["--host", options.host] : []
  ].flat()

/** @param {string} serveDir */
const ensureInitialized = (serveDir) =>
  !cacheIsCurrent()
    ? (console.log("No current template cache found; initializing it for this directory."), initializeCache(serveDir))
    : ((linkedDir) =>
        fs.realpathSync(serveDir) !== linkedDir
          ? (console.log(`Cache is configured for ${linkedDir}; serving ${serveDir} instead.`), initializeCache(serveDir))
          : undefined
      )(fs.realpathSync(PAGES_DIR))

/** @param {ServeOptions | BuildOptions} options @returns {NodeJS.ProcessEnv} */
const ssgEnv = (options) =>
  ( options.noDefaultPage || options.theme || options.css || options.menu ||
    ("edit" in options && options.edit)
    ? { ...process.env
      , ...options.noDefaultPage ? { SSG_NO_DEFAULT_PAGE: "1" } : {}
      , ...options.theme ? { SSG_THEME: options.theme } : {}
      , ...options.css ? { SSG_CSS_PATH: options.css } : {}
      , ...options.menu ? { SSG_MENU: "1" } : {}
      , ...("edit" in options && options.edit) ? { SSG_EDIT: "1" } : {}
      }
    : { ...process.env }
  )

/**
 * Install dependencies in the cache, then run an Astro command there.
 * @param {PackageManager} manager
 * @param {NodeJS.ProcessEnv} env
 * @param {() => Promise<void>} command
 * @returns {Promise<void>}
 */
const withInstalledCache = (manager, env, command) =>
  (console.log("installing dependencies"),
  run
    ( manager.command
    , manager.installArgs
    , { cwd: CACHE_DIR
      , env
      , shell: manager.shell
      }
    ).then((installCode) =>
      installCode !== 0
        ? (process.exitCode = installCode, undefined)
        : (pruneForeignLibcPackages(path.join(CACHE_DIR, "node_modules")), command())
    ))

/**
 * @param {PackageManager} manager
 * @param {NodeJS.ProcessEnv} env
 * @param {ServeOptions} options
 * @returns {Promise<void>}
 */
const runServe = (manager, env, options) =>
  withInstalledCache(manager, env, () =>
    run
      ( manager.command
      , manager.devArgs(astroArgsFromOptions(options))
      , { cwd: CACHE_DIR
        , env
        , shell: manager.shell
        }
      ).then((exitCode) => {
        process.exitCode = exitCode
      })
  )

/** @param {ServeOptions} options @returns {Promise<void>} */
const serve = async (options) =>
  (async (serveDir) =>
    ( checkNodeVersion()
    , assertCacheIsSafe(serveDir)
    , ensureInitialized(serveDir)
    , assertTypstAvailable(serveDir)
    , console.log(indexMessage(serveDir, options.noDefaultPage))
    , await runServe(packageManager(), ssgEnv(options), options)
    )
  )(resolveServeDir(options.dir))

/** @param {string} html @returns {string} */
const markGenerated = (html) =>
  /^<!doctype html>/i.test(html)
    ? html.replace(/^<!doctype html>/i, `<!doctype html>${GENERATED_HTML_MARKER}`)
    : `${GENERATED_HTML_MARKER}${html}`

/** @param {string} distDir @param {string} actual @returns {string} */
const builtHtmlFor = (distDir, actual) => {
  if (actual === "/404") return path.join(distDir, "404.html")
  const segments = actual.split("/").filter(Boolean)
  return segments.length === 0
    ? path.join(distDir, "index.html")
    : path.join(distDir, ...segments, "index.html")
}

/**
 * Copy each built page next to its source file as `<name>.html`. Files that
 * are already HTML stay untouched, and the built files are marked so `serve`
 * keeps preferring newer source files.
 *
 * @param {string} serveDir
 * @param {string} distDir
 */
const publishBuiltPages = (serveDir, distDir) => {
  let written = 0
  for (const page of listSourcePages(serveDir)) {
    const extension = path.posix.extname(page.file).toLowerCase()
    if (!BUILD_SOURCE_EXTENSIONS.includes(extension)) continue

    const built = builtHtmlFor(distDir, page.actual)
    if (!fs.existsSync(built)) {
      console.warn(`astro-ssg: no build output for ${page.file}; skipping.`)
      continue
    }

    const target = path.join(
      serveDir,
      `${page.file.slice(0, -extension.length)}.html`
    )
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, markGenerated(fs.readFileSync(built, "utf8")))
    written += 1
  }
  console.log(
    `Wrote ${written} HTML file${written === 1 ? "" : "s"} next to the source pages in ${serveDir}.`
  )
}

/**
 * @param {PackageManager} manager
 * @param {NodeJS.ProcessEnv} env
 * @returns {Promise<void>}
 */
const runBuild = (manager, env) =>
  withInstalledCache(manager, env, () =>
    run
      ( manager.command
      , manager.buildArgs
      , { cwd: CACHE_DIR
        , env
        , shell: manager.shell
        }
      ).then((exitCode) => {
        process.exitCode = exitCode
      })
  )

/** @param {BuildOptions} options @returns {Promise<void>} */
const build = async (options) =>
  (async (serveDir) =>
    ( checkNodeVersion()
    , assertCacheIsSafe(serveDir)
    , ensureInitialized(serveDir)
    , assertTypstAvailable(serveDir)
    , console.log(indexMessage(serveDir, options.noDefaultPage))
    , await runBuild(packageManager(), ssgEnv(options))
    , process.exitCode === 0
      ? publishBuiltPages(serveDir, path.join(CACHE_DIR, "dist"))
      : undefined
    )
  )(resolveServeDir(options.dir))

const cli = cac("astro-ssg")

cli
  .command("serve [dir]", "Copy the template to the cache if needed, then install dependencies and start the dev server")
  .option("--no-default-page", "Do not provide the missing-index page at /")
  .option("--theme [theme]", `Style every route with a stylesheet (${THEMES.join(", ")}); defaults to sakura`)
  .option("--css <file>", "Inject a .css file into every Astro-rendered, Typst, and built-in default page")
  .option("--menu", "Show a page-navigation menu button in the top-right corner")
  .option("--edit", "Make pages backed by .html/.md/.mdx sources editable in the browser and persist edits to disk")
  .option("--port <port>", "Port for the dev server")
  .option("--host [host]", "Expose the dev server on the network")
  .action(
    /** @param {string | undefined} dir @param {{ defaultPage?: boolean, theme?: boolean | string, css?: unknown, menu?: unknown, edit?: unknown, port?: unknown, host?: unknown }} options */
    (dir, options) =>
      serve
        ( { dir
          , noDefaultPage: options.defaultPage === false
          , theme: normalizeTheme(options.theme)
          , css: normalizeCss(options.css)
          , menu: Boolean(options.menu)
          , edit: Boolean(options.edit)
          , port: normalizePort(options.port)
          , host: normalizeHost(options.host)
          }
        )
  )

cli
  .command("build [dir]", "Compile every page to HTML next to its source file")
  .option("--no-default-page", "Do not provide the missing-index page at /")
  .option("--theme [theme]", `Style every route with a stylesheet (${THEMES.join(", ")}); defaults to sakura`)
  .option("--css <file>", "Inject a .css file into every Astro-rendered, Typst, and built-in default page")
  .option("--menu", "Show a page-navigation menu button in the top-right corner")
  .action(
    /** @param {string | undefined} dir @param {{ defaultPage?: boolean, theme?: boolean | string, css?: unknown, menu?: unknown }} options */
    (dir, options) =>
      build
        ( { dir
          , noDefaultPage: options.defaultPage === false
          , theme: normalizeTheme(options.theme)
          , css: normalizeCss(options.css)
          , menu: Boolean(options.menu)
          }
        )
  )

cli
  .command("themes", "List the available themes")
  .action(
    () =>
      ( console.log("Available themes (default: sakura):")
      , THEMES.forEach((theme) =>
          console.log(`  ${theme}${theme === DEFAULT_THEME ? " (default)" : ""}`)
        )
      , console.log("\nUse one with `astro-ssg serve --theme <theme>` or `astro-ssg build --theme <theme>`.")
      )
  )

cli.help((sections) =>
  sections.concat
    ( [ { title: "Cache"
        , body: `${CACHE_DIR}\nSet ASTRO_SSG_CACHE to use a different directory.`
        }
      ]
    )
)
cli.version(packageJson.version)

const parsed = cli.parse()

if (!cli.matchedCommand) {
  // cac already printed its own output for --help/--version.
  const cliOptions = /** @type {{ help?: unknown, version?: unknown }} */ (cli.options ?? {})
  cliOptions.help || cliOptions.version
    ? process.exit(0)
    : parsed.args.length === 0
      ? cli.outputHelp()
      : fail(`Unknown command "${parsed.args[0]}". This CLI has three commands: serve, build, and themes. See astro-ssg --help.`)
}
